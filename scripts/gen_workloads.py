#!/usr/bin/env python3
"""Generate one workload header per (config, mix, policy) for the harness.

  python3 scripts/gen_workloads.py                      # placeholder estimates
  python3 scripts/gen_workloads.py --single-core data/single_core.csv

Writes workloads/build/<Config>/<mix>.<policy>.h (sweep configs),
workloads/build/<Config>/single.h (1-core configs: every task once, for
characterization) and workloads/build/predictions.csv (predicted makespan per
run, for the contention comparison). Then build with `make -C workloads`.

Static policies (both from scripts/predict.py):
  speedup  proposal rule: tasks BOOM speeds up most go to BOOM cores
  eft      earliest finish time: longest task first, to the core that
           finishes it soonest
Homogeneous configs get only `eft` (the two policies coincide there).

single_core.csv columns: task,reps,rocket,smallboom,mediumboom (cycles for
`reps` repetitions, as written by parse_logs.py). Without it, every task is
estimated at 300k cycles on every core, so assignments only balance counts.
"""
import argparse, csv, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import predict  # noqa: E402

# Keep in the same order as the enum in workloads/tasks/tasks.h
TASKS = ["qsort", "brrand", "median", "ptrchase", "stream", "spmv",
         "matmul", "crc32", "fir"]

# name: (big core type or None, n_boom, n_rocket, roles)
CONFIGS = {
    "BudgetR1Config":    (None,         0, 1, {"single"}),
    "BudgetSB1Config":   ("smallboom",  1, 0, {"single"}),
    "BudgetMB1Config":   ("mediumboom", 1, 0, {"single", "sweep"}),
    "BudgetR4Config":    (None,         0, 4, {"sweep"}),
    "BudgetSB1R2Config": ("smallboom",  1, 2, {"sweep"}),
    "BudgetSB2Config":   ("smallboom",  2, 0, {"sweep"}),
}
TYPE_CODE = {"any": 0, "rocket": 1, "boom": 2}
PLACEHOLDER = 300_000


def load_estimates(path, task_reps):
    """Per-rep cycle estimates: {task: {"rocket": c, "smallboom": c, "mediumboom": c}}."""
    est = {t: {k: PLACEHOLDER for k in ("rocket", "smallboom", "mediumboom")} for t in TASKS}
    if not path:
        return est, False
    with open(path) as f:
        for row in csv.DictReader(f):
            t, reps = row["task"], max(1, int(row.get("reps") or 1))
            for k in ("rocket", "smallboom", "mediumboom"):
                if row.get(k):
                    est[t][k] = float(row[k]) / reps
    missing = [t for t in TASKS if t in task_reps and est[t]["rocket"] == PLACEHOLDER]
    if missing:
        print(f"warning: no single-core data for {missing}; using placeholders", file=sys.stderr)
    return est, True


def header(config, mix, policy, nharts, slots, note):
    """slots: list of (type_name, [(task, seed, reps), ...])"""
    lines = [f"// Generated by scripts/gen_workloads.py. {note}",
             f'#define WL_CONFIG "{config}"', f'#define WL_MIX "{mix}"',
             f'#define WL_POLICY "{policy}"', f"#define WL_NHARTS {nharts}",
             f"#define WL_NSLOTS {len(slots)}",
             f"#define WL_NTASKS {sum(len(s[1]) for s in slots)}",
             "static const int wl_slot_type[WL_NSLOTS] = {"
             + ", ".join(str(TYPE_CODE[t]) for t, _ in slots) + "};"]
    starts, n = [], 0
    for _, items in slots:
        starts.append(n); n += len(items)
    starts.append(n)
    lines.append("static const int wl_slot_start[WL_NSLOTS + 1] = {" + ", ".join(map(str, starts)) + "};")
    lines.append("static const wl_task_t wl_tasks[WL_NTASKS] = {")
    for si, (t, items) in enumerate(slots):
        lines.append(f"    // slot {si}: {t}")
        for task, seed, reps in items:
            lines.append(f"    {{ {TASKS.index(task)}, {seed}u, {reps} }},  // {task}")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mixes", default="workloads/mixes.json")
    ap.add_argument("--single-core", help="data/single_core.csv from parse_logs.py")
    ap.add_argument("--out", default="workloads/build")
    a = ap.parse_args()

    spec = json.load(open(a.mixes))
    task_reps = {t: v["reps"] for t, v in spec["tasks"].items()}
    for t in task_reps:
        if t not in TASKS:
            sys.exit(f"unknown task {t!r} in {a.mixes}")
    est, real = load_estimates(a.single_core, task_reps)
    note = "Estimates: " + ("single-core data" if real else "PLACEHOLDER (rerun with --single-core)")

    pred_rows = []
    for cfg, (big, nb, nr, roles) in CONFIGS.items():
        d = os.path.join(a.out, cfg)
        os.makedirs(d, exist_ok=True)
        nharts = nb + nr
        if "single" in roles:
            items = [(t, 1, task_reps[t]) for t in TASKS if t in task_reps]
            open(os.path.join(d, "single.h"), "w").write(
                header(cfg, "single", "none", 1, [("any", items)], note))
        if "sweep" not in roles:
            continue
        for mix, names in spec["mixes"].items():
            inst = [(f"{n}#{i}", n, i + 1, task_reps[n]) for i, n in enumerate(names)]
            by_id = {iid: (n, seed, reps) for iid, n, seed, reps in inst}
            tuples = [(iid, int(est[n]["rocket"] * reps),
                       int(est[n][big or "smallboom"] * reps)) for iid, n, _, reps in inst]
            policies = ["speedup", "eft"] if nb and nr else ["eft"]
            for pol in policies:
                cores = predict.assign(tuples, nb, nr) if pol == "speedup" else predict.assign_eft(tuples, nb, nr)
                slots = [(kind, [by_id[iid] for iid in names_]) for kind, _, names_ in cores]
                pred = max(load for _, load, _ in cores)
                open(os.path.join(d, f"{mix}.{pol}.h"), "w").write(
                    header(cfg, mix, pol, nharts, slots, note))
                pred_rows.append({"config": cfg, "mix": mix, "policy": pol,
                                  "predicted": pred, "estimates": "real" if real else "placeholder"})
                print(f"{cfg:18} {mix:9} {pol:8} predicted makespan {pred:>12,}")

    with open(os.path.join(a.out, "predictions.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["config", "mix", "policy", "predicted", "estimates"])
        w.writeheader(); w.writerows(pred_rows)
    if not real:
        print("\nNOTE: placeholder estimates. After the single-core runs, rerun with "
              "--single-core data/single_core.csv so the static policies use real numbers.")


if __name__ == "__main__":
    main()
